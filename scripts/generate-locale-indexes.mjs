#!/usr/bin/env node
/**
 * Write `web/messages/<locale>/index.ts` for every locale directory.
 *
 * Run after adding, renaming or removing a catalog:
 *   node scripts/generate-locale-indexes.mjs
 *
 * English is the source of truth: every locale index imports exactly the
 * catalogs in `web/messages/en`, keyed by the camel-cased file name
 * (`labor-pricing.json` becomes `laborPricing`). Each locale needs its own
 * file of static imports because the bundler must see every catalog at build
 * time. A locale that lacks one of those catalogs, or ships one English does
 * not, is refused by name instead of being written with a gap.
 */
import { readdirSync, statSync, writeFileSync } from 'node:fs'
import { join, relative } from 'node:path'

const ROOT = process.cwd()
const MESSAGES = join(ROOT, 'web', 'messages')
const SOURCE_LOCALE = 'en'

const catalogsOf = (locale) =>
  readdirSync(join(MESSAGES, locale))
    .filter((name) => name.endsWith('.json'))
    .map((name) => name.slice(0, -'.json'.length))
    .sort()

const namespaceKey = (file) => file.replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase())

const catalogs = catalogsOf(SOURCE_LOCALE)
const keys = new Map()
for (const file of catalogs) {
  const key = namespaceKey(file)
  if (!/^[A-Za-z_$][\w$]*$/.test(key)) {
    throw new Error(`${SOURCE_LOCALE}/${file}.json: "${key}" is not a usable namespace key; rename the file to lower-case words joined by hyphens.`)
  }
  if (keys.has(key)) {
    throw new Error(`${SOURCE_LOCALE}/${keys.get(key)}.json and ${SOURCE_LOCALE}/${file}.json both become namespace "${key}"; rename one of them.`)
  }
  keys.set(key, file)
}

const header = [
  '// GENERATED by scripts/generate-locale-indexes.mjs — do not edit by hand.',
  `// Every catalog in web/messages/${SOURCE_LOCALE}, keyed by its camel-cased file name, as`,
  '// the next-intl messages tree. Adding a namespace: create <ns>.json in every',
  '// locale directory, then rerun the generator.',
]
const body = [
  ...header,
  ...[...keys].map(([key, file]) => `import ${key} from './${file}.json'`),
  '',
  'export default {',
  ...[...keys.keys()].map((key) => `  ${key},`),
  '} as const',
  '',
].join('\n')

const locales = readdirSync(MESSAGES).filter((name) => !name.startsWith('.') && statSync(join(MESSAGES, name)).isDirectory()).sort()
const problems = []
for (const locale of locales) {
  const present = catalogsOf(locale)
  const missing = catalogs.filter((file) => !present.includes(file))
  const extra = present.filter((file) => !catalogs.includes(file))
  if (missing.length > 0) problems.push(`${locale} is missing catalogs English ships: ${missing.join(', ')}`)
  if (extra.length > 0) problems.push(`${locale} ships catalogs English does not: ${extra.join(', ')}`)
}
if (problems.length > 0) {
  throw new Error(`no index was written. Add each missing catalog to that locale, or add the extra one to ${SOURCE_LOCALE} as well:\n  ${problems.join('\n  ')}`)
}

for (const locale of locales) writeFileSync(join(MESSAGES, locale, 'index.ts'), body)
console.log(`wrote ${locales.length} locale indexes under ${relative(ROOT, MESSAGES)} — ${keys.size} namespaces each`)
