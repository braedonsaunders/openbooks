const AST_CACHE = new Map<string, MessageFormatElement[]>()
const AST_FAILURES = new Map<string, string>()

function astOf(locale: string, key: string, value: string): MessageFormatElement[] | null {
  const cacheKey = `${locale}:${key}`
  const cached = AST_CACHE.get(cacheKey)
  if (cached) return cached
  if (AST_FAILURES.has(cacheKey)) return null
  try {
    const parsed = parse(value)
    AST_CACHE.set(cacheKey, parsed)
    return parsed
  } catch (error) {
    AST_FAILURES.set(cacheKey, error instanceof Error ? error.message : String(error))
    return null
  }
}

function visitElements(
  elements: MessageFormatElement[],
  visit: (element: MessageFormatElement) => void,
): void {
  for (const element of elements) {
    visit(element)
    if (element.type === TYPE.plural || element.type === TYPE.select) {
      const options = (element as { options: Record<string, { value: MessageFormatElement[] }> }).options
      for (const option of Object.values(options)) visitElements(option.value, visit)
    }
    if (element.type === TYPE.tag) {
      visitElements((element as { children: MessageFormatElement[] }).children, visit)
    }
  }
}

/** Every interpolable name in the message, including ones nested inside plural arms and rich-text tags. */
function tokensOf(elements: MessageFormatElement[]): Set<string> {
  const tokens = new Set<string>()
  visitElements(elements, (element) => {
    if (
      element.type === TYPE.argument ||
      element.type === TYPE.number ||
      element.type === TYPE.date ||
      element.type === TYPE.time ||
      element.type === TYPE.plural ||
      element.type === TYPE.select
    ) {
      tokens.add((element as { value: string }).value)
    }
  })
  return tokens
}

/** Rich-text tag names (<b>, <link>, …) in walk order. */
function tagsOf(elements: MessageFormatElement[]): string[] {
  const tags: string[] = []
  visitElements(elements, (element) => {
    if (element.type === TYPE.tag) tags.push((element as { value: string }).value)
  })
  return tags
}

interface TypedBlock {
  arg: string
  kind: 'plural' | 'select' | 'selectordinal'
}

/** Plural/select/selectordinal blocks in walk order. */
function blocksOf(elements: MessageFormatElement[]): TypedBlock[] {
  const blocks: TypedBlock[] = []
  visitElements(elements, (element) => {
    if (element.type === TYPE.plural) {
      const pluralType = (element as { pluralType?: string }).pluralType
      blocks.push({
        arg: (element as { value: string }).value,
        kind: pluralType === 'ordinal' ? 'selectordinal' : 'plural',
      })
    } else if (element.type === TYPE.select) {
      blocks.push({ arg: (element as { value: string }).value, kind: 'select' })
    }
  })
  return blocks
}

interface PluralShape {
  arg: string
  /** Explicit selectors (=0, =1): behavioural copy, not inflection. */
  explicit: string[]
  /** CLDR category arms (one, other, …). */
  cats: string[]
}

/** Every plural block with its explicit selectors and category arms split apart. */
function pluralsOf(elements: MessageFormatElement[]): PluralShape[] {
  const shapes: PluralShape[] = []
  visitElements(elements, (element) => {
    if (element.type !== TYPE.plural) return
    const options = Object.keys((element as { options: Record<string, unknown> }).options)
    shapes.push({
      arg: (element as { value: string }).value,
      explicit: options.filter((name) => name.startsWith('=')).sort(),
      cats: options.filter((name) => !name.startsWith('=')).sort(),
    })
  })
  return shapes
}

/** The independent source for which plural categories a locale distinguishes. */
function pluralCategories(locale: string): string[] {
  return new Intl.PluralRules(locale).resolvedOptions().pluralCategories
}

/**
 * Japanese and Chinese distinguish only other: one bare {count} form renders
 * correctly for every count, so their translations may simplify or drop a
 * plural block. Every other shipped locale inflects, so its structure must
 * match the source.
 */
function isSingleFormLocale(locale: string): boolean {
  const cats = pluralCategories(locale)
  return cats.length === 1 && cats[0] === 'other'
}

function blockSignature(blocks: TypedBlock[]): string[] {
  return blocks.map((block) => `${block.arg}:${block.kind}`)
}

