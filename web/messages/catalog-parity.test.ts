/**
 * Locale parity as derived rules over the assembled message catalogs.
 *
 * The shipped locales come from the app's locale config (web/i18n/config.ts),
 * never a literal list: adding a language there extends every rule below to
 * it with no test change. Each locale is loaded through its assembled index
 * (web/messages/<locale>/index.ts) — the same tree next-intl serves — so
 * namespace renames (laborPricing from labor-pricing.json, continuousClose
 * from continuous-close.json) resolve exactly as the app resolves them, and
 * message arrays flatten by index (sync.sources.qbo.steps.0) because the
 * runtime deep-merge turns arrays into objects before next-intl sees them.
 *
 * The rules:
 * 1. Every English key exists non-empty in every shipped locale.
 * 2. ICU arguments ({name}, {count}) and rich-text tags are the same set per
 *    key; plural/select structure matches; plurals cover the locale's CLDR
 *    categories (see pluralCovers for the single-form-language exemption).
 * 3. No locale ships the English string verbatim except declared cognates.
 * 4. No locale carries keys English does not have.
 * 5. Every message parses as valid ICU (the same parser family next-intl
 *    formats with, so a red here is a render-time crash or garbage avoided).
 *
 * Rule 3 needs a word on single-form languages. Japanese and Chinese have a
 * single plural category (other): one bare {count} form is correct for every
 * count, so a translation may simplify or drop the plural block. French,
 * Spanish and Portuguese distinguish one/many/other at the CLDR level, but
 * their UI copy never distinguishes many (millions and above fall back to
 * other by ICU design, correctly for these strings), so coverage means: every
 * category the SOURCE distinguishes that is meaningful in the locale must
 * survive. Dropping one in French renders "1 éléments" — that fails.
 */

const SHIPPED_LOCALES = LOCALES.map((entry) => entry.code)
const SOURCE_LOCALE = 'en'
const MESSAGES_DIR = join(import.meta.dirname)

interface LocaleCatalog {
  code: string
  leaves: Map<string, string>
  dotted: string[]
}

/**
 * Flatten one assembled locale tree. Arrays flatten by index because the
 * runtime deep-merge (web/i18n/request.ts) turns arrays into objects before
 * next-intl resolves them — a bare object walk would silently skip array
 * leaves and an array-vs-object shape mismatch would be invisible.
 */
function flattenNamespaces(messages: Record<string, unknown>): {
  leaves: Map<string, string>
  dotted: string[]
} {
  const leaves = new Map<string, string>()
  const dotted: string[] = []
  const visit = (node: unknown, path: string): void => {
    if (typeof node === 'string') {
      leaves.set(path, node)
      return
    }
    if (Array.isArray(node)) {
      node.forEach((entry, index) => visit(entry, `${path}.${index}`))
      return
    }
    if (node !== null && typeof node === 'object') {
      for (const [key, value] of Object.entries(node)) {
        if (key.includes('.')) dotted.push(`${path}.${key}`)
        visit(value, path ? `${path}.${key}` : key)
      }
    }
  }
  for (const [namespace, tree] of Object.entries(messages)) visit(tree, namespace)
  return { leaves, dotted }
}

async function loadCatalogs(): Promise<LocaleCatalog[]> {
  const catalogs: LocaleCatalog[] = []
  for (const code of SHIPPED_LOCALES) {
    const assembled = (await import(`./${code}/index.ts`)).default as Record<string, unknown>
    const { leaves, dotted } = flattenNamespaces(assembled)
    catalogs.push({ code, leaves, dotted })
  }
  return catalogs
}

