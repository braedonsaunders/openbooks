test('ICU arguments and rich-text tags match English for every key', () => {
  const offenders: string[] = []
  for (const catalog of OTHER_CATALOGS) {
    for (const [key, sourceValue] of EN_LEAVES) {
      const value = catalog.leaves.get(key)
      if (value === undefined || value.trim() === '') continue
      const sourceAst = astOf(SOURCE_LOCALE, key, sourceValue)
      const ast = astOf(catalog.code, key, value)
      if (sourceAst === null || ast === null) continue
      const expected = [...tokensOf(sourceAst)].sort()
      const actual = [...tokensOf(ast)].sort()
      const drifted =
        expected.length !== actual.length || expected.some((token) => !actual.includes(token))
      if (drifted) {
        offenders.push(
          `${catalog.code}:${key} drops or renames ICU arguments (en {${expected.join('} {')}} vs ${catalog.code} {${actual.join('} {')}})`,
        )
        continue
      }
      const expectedTags = tagsOf(sourceAst).sort()
      const actualTags = tagsOf(ast).sort()
      if (expectedTags.join(',') !== actualTags.join(',')) {
        offenders.push(
          `${catalog.code}:${key} changes rich-text tags (en <${expectedTags.join('><')}>, ${catalog.code} <${actualTags.join('><')}>)`,
        )
      }
    }
  }
  assert.deepEqual(
    offenders,
    [],
    `${offenders.length} translations interpolate differently than English (values render undefined or raw markup):\n  ${sample(offenders)}`,
  )
})

test('plural and select structure matches English and covers each locale\u2019s plural categories', () => {
  const offenders: string[] = []
  for (const catalog of OTHER_CATALOGS) {
    const cats = pluralCategories(catalog.code)
    const singleForm = isSingleFormLocale(catalog.code)
    for (const [key, sourceValue] of EN_LEAVES) {
      const value = catalog.leaves.get(key)
      if (value === undefined || value.trim() === '') continue
      const sourceAst = astOf(SOURCE_LOCALE, key, sourceValue)
      const ast = astOf(catalog.code, key, value)
      if (sourceAst === null || ast === null) continue
      if (!singleForm) {
        // A translation may ADD a plural the source lacks (French number
        // agreement around an existing {count} renders correctly because the
        // caller already passes the value), but it must never DROP or
        // retype a source block: rendering then picks the wrong branch.
        const expected = blockSignature(blocksOf(sourceAst))
        const actual = blockSignature(blocksOf(ast))
        const dropped = expected.filter((block) => !actual.includes(block))
        if (dropped.length > 0) {
          offenders.push(
            `${catalog.code}:${key} drops plural/select blocks [${dropped.join('|')}] (en [${expected.join('|')}] vs [${actual.join('|')}])`,
          )
          continue
        }
      }
      const sourcePlurals = pluralsOf(sourceAst)
      if (sourcePlurals.length === 0) continue
      const actualPlurals = pluralsOf(ast)
      for (const sourcePlural of sourcePlurals) {
        const matches = actualPlurals.filter((shape) => shape.arg === sourcePlural.arg)
        if (matches.length === 0) {
          // Single-form languages render every count with one form, so the
          // bare {count} template covers all their categories. Anywhere else
          // a dropped plural renders the wrong form ("1 éléments").
          if (!singleForm) offenders.push(`${catalog.code}:${key} drops the {${sourcePlural.arg}} plural`)
          continue
        }
        // Coverage means every category the source distinguishes that is
        // meaningful in this locale survives. Categories the source never
        // distinguished (fr many) fall back to other by ICU design, which is
        // correct for this copy — inventing a many arm would be noise.
        const need = cats.filter((cat) => sourcePlural.cats.includes(cat) || cat === 'other')
        const have = new Set(matches.flatMap((shape) => shape.cats))
        const missingCats = need.filter((cat) => !have.has(cat))
        if (missingCats.length > 0) {
          offenders.push(
            `${catalog.code}:${key} {${sourcePlural.arg}} misses plural categories ${missingCats.join(',')} (locale needs ${need.join(',')})`,
          )
        }
        if (!singleForm) {
          const expectedExplicit = sourcePlural.explicit.join(',')
          for (const match of matches) {
            if (match.explicit.join(',') !== expectedExplicit) {
              offenders.push(
                `${catalog.code}:${key} {${sourcePlural.arg}} changes explicit selectors (en [${expectedExplicit}] vs [${match.explicit.join(',')}])`,
              )
            }
          }
        }
      }
    }
  }
  assert.deepEqual(
    offenders,
    [],
    `${offenders.length} translations break plural behaviour:\n  ${sample(offenders)}`,
  )
})

